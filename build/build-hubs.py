HUBS = {
    'learn': {
        'file': 'learn.html',
        'heading': 'Every article',
        'tag': 'The full index',
        'lede': 'Everything published so far, in one place. '
                'Start anywhere. There is no order you are meant to follow.',
    },
    'foods': {
        'file': 'foods-hub.html',
        'heading': 'Every food guide',
        'tag': 'The full index',
        'lede': 'Every food, ingredient and meal guide published so far. '
                'Start with what is already in your kitchen.',
    },
}


def text_of(fragment):
    """Readable text from an H1 that uses <br> for line breaks."""
    fragment = re.sub(r'<br\s*/?>', ' ', fragment)
    fragment = re.sub(r'<[^>]+>', '', fragment)
    return re.sub(r'\s+', ' ', fragment).strip()


def read(path):
    with open(path, encoding='utf-8') as fh:
        return fh.read()


def metadata(filename):
    html = read(os.path.join(ROOT, filename))

    h1 = re.search(r'<h1[^>]*>(.*?)</h1>', html, re.S)
    title = text_of(h1.group(1)) if h1 else filename

    desc = re.search(r'<meta name="description" content="([^"]*)"', html)
    excerpt = desc.group(1) if desc else ''

    # A description that is really the page title plus a stock brand sentence
    # says nothing about the article and makes a useless card. migrate.py
    # rewrites the five known offenders; this stays as a guard in case a new
    # page ships with the same pattern.
    if excerpt.count('—') >= 2 and 'Kwik Fat Cut' in excerpt[:120]:
        lede = re.search(r'class="(?:lede|hero-lede)"[^>]*>(.*?)</p>', html, re.S)
        if lede:
            excerpt = text_of(lede.group(1))
        metadata.weak_descriptions.append(filename)

    excerpt = re.split(r'(?<=[.!?])\s+', excerpt)
    excerpt = ' '.join(excerpt[:2]).strip()

    tag = re.search(r'class="(?:article-tag|section-tag)"[^>]*>(.*?)<', html, re.S)
    label = text_of(tag.group(1)) if tag else 'Article'
    # Tags often append a series name after a dash. The first part is the
    # useful part on a card.
    label = re.split(r'\s+[-–—]\s+', label)[0].strip()

    body = re.sub(r'<(script|style)\b.*?</\1>', '', html, flags=re.S)
    words = len(re.findall(r'\w+', re.sub(r'<[^>]+>', ' ', body)))
    minutes = max(2, round(words / WORDS_PER_MINUTE))

    return {
        'href': filename,
        'title': title,
        'excerpt': excerpt,
        'label': label,
        'minutes': minutes,
    }


metadata.weak_descriptions = []


def escape(text):
    return (text.replace('&', '&amp;')
                .replace('<', '&lt;')
                .replace('>', '&gt;')
                .replace('"', '&quot;'))


def card(meta):
    """Matches the existing .article-card markup, gold arrow included."""
    return (
        '      <a href="%s" class="article-card reveal">\n'
        '        <div>\n'
        '          <p class="ac-tag">%s</p>\n'
        '          <h3 class="ac-title">%s</h3>\n'
        '          <p class="ac-excerpt">%s</p>\n'
        '        </div>\n'
        '        <div class="ac-footer">\n'
        '          <span class="ac-meta">%d min read</span>\n'
        '          <span class="ac-arrow">&rarr;</span>\n'
        '        </div>\n'
        '      </a>'
    ) % (meta['href'], escape(meta['label']), escape(meta['title']),
         escape(meta['excerpt']), meta['minutes'])


def section(key, articles):
    spec = HUBS[key]
    cards = '\n'.join(card(a) for a in articles)
    return (
        '%s\n'
        '  <section class="kfc-index">\n'
        '    <div class="kfc-index-head reveal">\n'
        '      <p class="section-tag">%s</p>\n'
        '      <h2 class="section-title">%s</h2>\n'
        '      <p class="lede">%s</p>\n'
        '    </div>\n'
        '    <div class="kfc-index-grid">\n'
        '%s\n'
        '    </div>\n'
        '  </section>\n'
        '  %s'
    ) % (START, escape(spec['tag']), escape(spec['heading']),
         escape(spec['lede']), cards, END)


def inject(key, block):
    spec = HUBS[key]
    path = os.path.join(ROOT, spec['file'])
    html = read(path)

    if START in html and END in html:
        out = re.sub(re.escape(START) + r'.*?' + re.escape(END), lambda m: block,
                     html, flags=re.S)
    else:
        # Before the share strip if there is one, otherwise before the footer.
        anchor = re.search(r'\n\s*<section class="(?:ss|social)[^"]*"', html)
        pos = anchor.start() if anchor else html.rfind('</main>')
        if pos == -1:
            pos = html.rfind('<footer')
        out = html[:pos] + '\n' + block + '\n' + html[pos:]

    changed = out != html
    if changed and not DRY:
        with open(path, 'w', encoding='utf-8') as fh:
            fh.write(out)
    return changed


def main():
    known = set(HUB)
    present = {os.path.basename(p) for p in glob.glob(os.path.join(ROOT, 'learn-*.html'))}
    present.add('opian-meals.html')

    missing = sorted(present - known)
    stale = sorted(known - present)
    if missing:
        print('NOT IN ANY HUB, add them to HUB in this file:')
        for m in missing:
            print('   ', m)
    if stale:
        print('LISTED BUT NOT ON DISK:')
        for s in stale:
            print('   ', s)

    buckets = {'learn': [], 'foods': []}
    for name in sorted(known & present):
        buckets[HUB[name]].append(metadata(name))

    for key in ('learn', 'foods'):
        articles = sorted(buckets[key], key=lambda a: a['title'].lower())
        changed = inject(key, section(key, articles))
        print('%-18s %2d articles indexed   %s' %
              (HUBS[key]['file'], len(articles),
               'updated' if changed else 'no change'))

    if metadata.weak_descriptions:
        print('\nBoilerplate meta descriptions still present, card text fell '
              'back to the page lede:')
        for f in metadata.weak_descriptions:
            print('   ', f)

    if DRY:
        print('\nDRY RUN: nothing written.')


if __name__ == '__main__':
    main()
