#!/usr/bin/env python3
"""
Kwik Fat Cut hub linking.

Generates a complete article index on learn.html and foods-hub.html, built
from metadata that already exists on each article page. No new copy is
invented: the title comes from the article's own H1, the excerpt from its
meta description, the label from its own tag, the read time from its word
count.

Why this exists. The two hubs between them linked 13 of 35 articles. Ten
articles had no inbound content link anywhere on the site, which is the most
likely reason indexing is incomplete: crawlers find pages by following links,
and there was nothing to follow. Milestone 1 in MANIFEST.txt requires every
preview card to carry a read-more arrow matching the existing gold pattern,
which the generated cards do.

Run after migrate.py, and re-run whenever an article is added or retitled:

    python3 build/build-hubs.py
    python3 build/build-hubs.py --dry-run

Idempotent. The generated block is fenced by HTML comments and replaced whole
on each run, so hand-curated featured cards above it are never touched.
"""

import os
import re
import sys
import glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DRY = '--dry-run' in sys.argv

START = '<!-- KFC:INDEX START  generated by build/build-hubs.py, do not edit by hand -->'
END = '<!-- KFC:INDEX END -->'

WORDS_PER_MINUTE = 200

# Which hub each article belongs to. Foods Hub takes anything about a specific
# food, ingredient or meal; Learn takes concepts, science and practice. Set
# explicitly rather than guessed from the filename, so a rename cannot silently
# move an article to the wrong hub.
